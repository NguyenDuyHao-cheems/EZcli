"""Core domain models for EZcli."""

from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum


class SafetyLevel(StrEnum):
    """Safety classification for a generated command."""

    SAFE = "safe"
    WARNING = "warning"
    BLOCKED = "blocked"


class ExecutionStatus(StrEnum):
    """Execution status recorded in command history."""

    PENDING = "pending"
    SUCCESS = "success"
    FAILED = "failed"
    CANCELLED = "cancelled"
    BLOCKED = "blocked"


@dataclass(frozen=True)
class CommandRequest:
    """Natural-language request submitted by the user."""

    prompt: str


@dataclass(frozen=True)
class GeneratedCommand:
    """Command generated by the local LLM."""

    prompt: str
    command: str
    explanation: str = ""


@dataclass(frozen=True)
class SafetyResult:
    """Result returned by the safety checker."""

    level: SafetyLevel
    reasons: tuple[str, ...] = ()


@dataclass(frozen=True)
class HistoryEntry:
    """A locally stored command operation."""

    prompt: str
    command: str
    timestamp: datetime
    safety: SafetyLevel
    status: ExecutionStatus
    exit_code: int | None = None
